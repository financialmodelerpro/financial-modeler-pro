/**
 * gen-refm-session-content.ts: turns the founder's content file
 * (docs/REFM_Live_Course_Materials/REFM_Session_Content.md, git-ignored with
 * the materials) into src/hubs/training/lib/liveCourse/seeds/refmSessionContent.ts,
 * which IS committed and is what scripts/seed-refm-sessions.ts writes.
 *
 * Refuses (writes nothing) unless the file parses to sessions 1 to 8, each with
 * every section filled.
 *
 * Run: npx tsx scripts/gen-refm-session-content.ts
 */
import { readFileSync, writeFileSync } from 'fs';
import { parseSessionContentMd, SECTION_KEYS } from '../src/hubs/training/lib/liveCourse/sessionContent';

const SRC = 'docs/REFM_Live_Course_Materials/REFM_Session_Content.md';
const OUT = 'src/hubs/training/lib/liveCourse/seeds/refmSessionContent.ts';

const parsed = parseSessionContentMd(readFileSync(SRC, 'utf8'));
const problems: string[] = [];
if (parsed.map((p) => p.no).join(',') !== '1,2,3,4,5,6,7,8') problems.push(`sessions found: ${parsed.map((p) => p.no).join(',')}`);
for (const p of parsed) for (const k of SECTION_KEYS) if (!p.sections[k].length) problems.push(`Session ${p.no}: ${k} is empty`);
if (problems.length) { console.error(`Refused, nothing written:\n  ${problems.join('\n  ')}`); process.exit(1); }

const body = parsed.map((p) => `  ${p.no}: ${JSON.stringify(p.sections, null, 2).replace(/\n/g, '\n  ')},`).join('\n');
writeFileSync(OUT, `/**
 * The REFM live course's session page content (founder, 2026-11-10): eight
 * lists per session (liveCourse/sessionContent.ts), keyed by session number.
 * GENERATED by scripts/gen-refm-session-content.ts from
 * ${SRC}; edit the file and regenerate, or edit a
 * session in Admin > Live Training > REFM > Sessions.
 */
import type { SessionSections } from '../sessionContent';

export const REFM_SESSION_CONTENT: Record<number, SessionSections> = {
${body}
};
`, 'utf8');
console.log(`Wrote ${OUT}: ${parsed.length} sessions, ${parsed.reduce((n, p) => n + SECTION_KEYS.reduce((m, k) => m + p.sections[k].length, 0), 0)} items.`);
